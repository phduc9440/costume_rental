package com.costume_rental.costume_service.exception;

import org.springframework.http.HttpStatus;
import org.springframework.http.HttpStatusCode;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.experimental.FieldDefaults;

@Getter
@FieldDefaults(level = AccessLevel.PRIVATE, makeFinal = true)
public enum ErrorCode {
    UNCATEGORIZED_EXCEPTION(9999, "Uncategorized error", HttpStatus.INTERNAL_SERVER_ERROR),
    UNAUTHENTICATED(1001, "Unauthenticated", HttpStatus.UNAUTHORIZED),
    UNAUTHORIZED(1002, "You do not have permission", HttpStatus.FORBIDDEN),

    COSTUME_NOT_EXISTED(1301, "Costume not existed", HttpStatus.NOT_FOUND),
    COSTUME_NAME_EXISTED(1302, "Costume name already exists", HttpStatus.BAD_REQUEST),
    INSUFFICIENT_STOCK(1303, "Insufficient stock", HttpStatus.BAD_REQUEST),
    INVALID_QUANTITY(1304, "Invalid quantity", HttpStatus.BAD_REQUEST),
    ;

    int code;
    String message;
    HttpStatusCode httpStatusCode;

    ErrorCode(int code, String message, HttpStatusCode httpStatusCode) {
        this.code = code;
        this.message = message;
        this.httpStatusCode = httpStatusCode;
    }
}
